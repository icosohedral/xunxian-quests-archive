def _relation(
    bridge: tuple[Any, ...],
    source_row: int,
    *,
    relation_type: str,
) -> dict[str, Any]:
    from_quest_id, from_quest_name, to_quest_id, to_quest_name = bridge[:4]
    if relation_type == "completion_requirement":
        inference_basis = "后任务明确要求完成前任务"
        confidence = "confirmed"
        inferred = False
        relation_label = "明确衔接"
        source_file = "mb/quest/quest_info.txt"
        run_id = "20260725-character-calls"
    else:
        inference_basis, confidence = bridge[4:]
        inferred = True
        relation_label = "版本衔接"
        source_file = "curated/version_update_bridges"
        run_id = "curated-20260727"
    return {
        "relation_id": None,
        "from_quest_id": from_quest_id,
        "from_version_no": 1,
        "from_quest_name": from_quest_name,
        "to_quest_id": to_quest_id,
        "to_quest_name": to_quest_name,
        "relation_type": relation_type,
        "relation_label": relation_label,
        "slot_no": source_row,
        "source_file": source_file,
        "source_row": source_row,
        "run_id": run_id,
        "inferred": inferred,
        "confidence": confidence,
        "inference_basis": inference_basis,
    }


def story_context_relations(quest_id: int) -> dict[str, list[dict[str, Any]]]:
    incoming: list[dict[str, Any]] = []
    outgoing: list[dict[str, Any]] = []
    groups = (
        ("completion_requirement", CONFIRMED_COMPLETION_BRIDGES),
        ("version_update", VERSION_UPDATE_BRIDGES),
    )
    for relation_type, bridges in groups:
        for source_row, bridge in enumerate(bridges, start=1):
            relation = _relation(
                bridge,
                source_row,
                relation_type=relation_type,
            )
            if relation["from_quest_id"] == quest_id:
                outgoing.append(relation)
            if relation["to_quest_id"] == quest_id:
                incoming.append(relation)
    return {"incoming": incoming, "outgoing": outgoing}
